//! OCR prompt 模板。做成常量便于调优；改动 prompt 时必须递增 PROMPT_VERSION 使旧缓存失效。

/// prompt 结构/措辞的版本号，页级缓存命中条件之一。
pub const PROMPT_VERSION: u32 = 1;

/// 考试教材场景定制的识别 prompt（v1 固定中文）。
pub const OCR_PROMPT: &str = r#"请识别这一页扫描文档的全部内容，输出为 Markdown。要求：
1. 忠实转录所有文字，保持原有阅读顺序，不要总结、不要遗漏、不要评论
2. 保留题目编号、选项标记（A. B. C. D.）、章节标题层级（用 #/##/###）
3. 数学公式用 LaTeX 表示，行内公式用 $...$，独立公式用 $$...$$
4. 表格转录为 Markdown 表格
5. 无文字的插图、图表，用一行 [图: 简要描述] 占位
6. 页眉页脚、页码、水印等无关内容忽略
7. 除 Markdown 正文外，不要输出任何其他内容"#;
